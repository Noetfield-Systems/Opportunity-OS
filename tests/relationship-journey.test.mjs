import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const app=fs.readFileSync(new URL("../public/app.js",import.meta.url),"utf8");
const html=fs.readFileSync(new URL("../public/index.html",import.meta.url),"utf8");
const css=fs.readFileSync(new URL("../public/styles.css",import.meta.url),"utf8");
test("relationship journey is a human-readable, real stage lens, not a payments simulator",()=>{
  assert.match(html,/id="caseJourney"/);
  assert.match(html,/id="journeyState"/);
  assert.match(css,/\.journey-station\.current/);
  assert.match(css,/max-width:570px/);
  const start=app.indexOf("function renderCaseJourney(x){");
  const end=app.indexOf("function renderDialog(x){",start);
  assert.ok(start>0&&end>start);
  const nodes={caseJourney:{innerHTML:""},journeyState:{textContent:""}};
  const ctx={String,Math,$:id=>nodes[id],h:x=>String(x||""),text:(id,value)=>{nodes[id].textContent=value}};
  vm.runInNewContext(app.slice(start,end),ctx);
  vm.runInNewContext('renderCaseJourney({stage:"NEW"})',ctx);
  assert.equal(nodes.journeyState.textContent,"Received");
  assert.equal((nodes.caseJourney.innerHTML.match(/journey-station /g)||[]).length,7);
  assert.equal((nodes.caseJourney.innerHTML.match(/journey-station current/g)||[]).length,1);
  assert.match(nodes.caseJourney.innerHTML,/Not recorded yet/);
  vm.runInNewContext('renderCaseJourney({stage:"ENGAGED"})',ctx);
  assert.equal(nodes.journeyState.textContent,"Connect");
  assert.match(nodes.caseJourney.innerHTML,/Earlier stage inferred from sequence/);
  vm.runInNewContext('renderCaseJourney({stage:"WON"})',ctx);
  assert.equal(nodes.journeyState.textContent,"Recorded win");
  assert.doesNotMatch(nodes.caseJourney.innerHTML,/Payment collected/);
  vm.runInNewContext('renderCaseJourney({stage:"LOST"})',ctx);
  assert.equal(nodes.journeyState.textContent,"Closed · not won");
  assert.match(nodes.caseJourney.innerHTML,/Historical stages not verified/);
});